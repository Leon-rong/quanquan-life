function getMonthly(table, months) {
  if (months < 0) months = 0;
  if (months > 36) months = 36;
  const lo = Math.floor(months);
  const hi = Math.ceil(months);
  const f = months - lo;
  const a = table[lo] || table[table.length - 1];
  const b = table[hi] || a;
  return a.map((v, i) => Math.round((v + (b[i] - v) * f) * 100) / 100);
}

function getByKey(obj, months) {
  const keys = Object.keys(obj).map(Number).sort((a, b) => a - b);
  if (months <= keys[0]) return obj[keys[0]];
  if (months >= keys[keys.length - 1]) return obj[keys[keys.length - 1]];
  let lo = keys[0], hi = keys[keys.length - 1];
  for (let i = 0; i < keys.length - 1; i++) {
    if (months >= keys[i] && months <= keys[i + 1]) { lo = keys[i]; hi = keys[i + 1]; break; }
  }
  const f = (months - lo) / (hi - lo);
  const a = obj[lo], b = obj[hi];
  return a.map((v, i) => Math.round((v + (b[i] - v) * f) * 100) / 100);
}

function evaluatePercentile(value, pcts) {
  if (value == null || Number.isNaN(value)) return { pct: null, level: null, label: '暂无数据' };
  if (value >= pcts[6]) return { pct: 97, level: 'high', label: '上等' };
  if (value >= pcts[4]) return { pct: 90, level: 'high-norm', label: '中上' };
  if (value >= pcts[2]) return { pct: 50, level: 'norm', label: '中等' };
  if (value >= pcts[0]) return { pct: 10, level: 'low-norm', label: '中下' };
  return { pct: 3, level: 'low', label: '下等' };
}

function bmi(weightKg, heightCm) {
  if (!weightKg || !heightCm) return null;
  const m = heightCm / 100;
  return Math.round(weightKg / (m * m) * 10) / 10;
}

export function ageMonths(birthDateStr, now = new Date()) {
  const birth = new Date(birthDateStr);
  const months = (now.getFullYear() - birth.getFullYear()) * 12 + (now.getMonth() - birth.getMonth());
  const dayAdj = now.getDate() < birth.getDate() ? -1 : 0;
  return months + dayAdj;
}

export function evaluateGrowth({ sex, birthDate, weight, height, head }, now = new Date()) {
  const months = ageMonths(birthDate, now);
  const isBoy = sex === 'boy' || sex === 'male' || sex === '男';
  const wTable = isBoy ? BOY_WEIGHT : GIRL_WEIGHT;
  const hTable = isBoy ? BOY_HEIGHT : GIRL_HEIGHT;
  const hdTable = isBoy ? BOY_HEAD : GIRL_HEAD;

  const weightPcts = getMonthly(wTable, months);
  const heightPcts = getByKey(hTable, months);
  const headPcts = getMonthly(hdTable, months);

  const weightEval = evaluatePercentile(weight, weightPcts);
  const heightEval = evaluatePercentile(height, heightPcts);
  const headEval = evaluatePercentile(head, headPcts);
  const bmiVal = bmi(weight, height);

  return {
    months,
    bmi: bmiVal,
    weight: { value: weight, ...weightEval, pcts: weightPcts },
    height: { value: height, ...heightEval, pcts: heightPcts },
    head: { value: head, ...headEval, pcts: headPcts },
  };
}

function classifyBmi(bmiVal, months) {
  if (bmiVal == null) return null;
  // 简化：2 岁以内用身长别体重更准确，此处仅做粗略营养提示
  if (months < 24) {
    if (bmiVal >= 19) return { label: '体重偏快', risk: 2 };
    if (bmiVal <= 15) return { label: '体重偏轻', risk: 2 };
    return { label: '匀称', risk: 0 };
  }
  if (bmiVal >= 18) return { label: '超重风险', risk: 2 };
  if (bmiVal >= 17) return { label: '体重偏快', risk: 1 };
  if (bmiVal <= 14.5) return { label: '体重偏轻', risk: 2 };
  return { label: '匀称', risk: 0 };
}

export function growthAdvice(evalResult) {
  const { weight, height, head, bmi, months } = evalResult;
  const parts = [];
  let overallRisk = 0;

  if (weight.level === 'low') { parts.push('体重处于同龄儿童较低水平，建议关注喂养量与营养密度，必要时咨询儿科医生。'); overallRisk = Math.max(overallRisk, 2); }
  else if (weight.level === 'low-norm') { parts.push('体重略低于中等水平，可增加优质蛋白、奶量及辅食多样性。'); overallRisk = Math.max(overallRisk, 1); }
  else if (weight.level === 'high') { parts.push('体重超过 97% 同龄儿童，注意避免过度喂养，增加大运动时间。'); overallRisk = Math.max(overallRisk, 1); }
  else { parts.push('体重水平良好，保持当前喂养节奏。'); }

  if (height.level === 'low') { parts.push('身高/身长明显落后，建议儿童保健科评估，排除慢性疾病或内分泌问题。'); overallRisk = Math.max(overallRisk, 2); }
  else if (height.level === 'low-norm') { parts.push('身高/身长稍偏中下，保证奶量、维生素 D、睡眠与户外活动。'); overallRisk = Math.max(overallRisk, 1); }
  else if (height.level === 'high') { parts.push('身高/身长非常突出，继续均衡营养，定期监测即可。'); }
  else { parts.push('身高/身长处于正常范围。'); }

  if (head.level === 'low') { parts.push('头围偏小，建议儿科或儿童保健科进一步检查。'); overallRisk = Math.max(overallRisk, 2); }
  else if (head.level === 'high') { parts.push('头围偏大，若持续快速增长需排除异常，建议随访。'); overallRisk = Math.max(overallRisk, 1); }
  else { parts.push('头围发育正常。'); }

  const bmiState = classifyBmi(bmi, months);
  if (bmiState && bmiState.risk > 0) { parts.push(`BMI 评价：${bmiState.label}。`); overallRisk = Math.max(overallRisk, bmiState.risk); }

  const status = overallRisk === 2 ? '需关注' : overallRisk === 1 ? '可优化' : '良好';
  return { advice: parts, status, risk: overallRisk, bmiState };
}

export function evaluateTrend(records, birthDate, sex) {
  // records: [{ ts, weight, height, head }, ...]
  const sorted = [...records].filter((r) => r.weight || r.height).sort((a, b) => a.ts - b.ts);
  if (sorted.length < 2) return null;
  const first = sorted[0], last = sorted[sorted.length - 1];
  const days = Math.max(1, (last.ts - first.ts) / 86400000);
  const months = days / 30.44;
  const wDelta = last.weight && first.weight ? (last.weight - first.weight) / months : null;
  const hDelta = last.height && first.height ? (last.height - first.height) / months : null;

  const lastEval = evaluateGrowth({ sex, birthDate, weight: last.weight, height: last.height, head: last.head }, new Date(last.ts));
  const prev = sorted[sorted.length - 2];
  const prevEval = evaluateGrowth({ sex, birthDate, weight: prev.weight, height: prev.height, head: prev.head }, new Date(prev.ts));

  const crossing = [];
  ['weight','height','head'].forEach((k) => {
    const a = prevEval[k].pct, b = lastEval[k].pct;
    if (a != null && b != null) {
      if (a < 25 && b >= 25) crossing.push(`${k === 'weight' ? '体重' : k === 'height' ? '身高' : '头围'}从偏低区间回升到中等区间，进步明显`);
      else if (a >= 75 && b < 75) crossing.push(`${k === 'weight' ? '体重' : k === 'height' ? '身高' : '头围'}从中上区间回落，留意喂养/睡眠`);
    }
  });

  return {
    days: Math.round(days),
    monthlyWeightGain: wDelta ? Math.round(wDelta * 100) / 100 : null,
    monthlyHeightGain: hDelta ? Math.round(hDelta * 100) / 100 : null,
    crossing,
  };
}
